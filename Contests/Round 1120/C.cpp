#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t;
    cin >> t;

    while (t--) {
        ll n;
        cin >> n;
        vector<ll> vec(n);
        for (int i = 0; i < n; i++) cin >> vec[i];
        set<ll>s;
        for(int i=0;i<n;i++){
            s.insert(i);
        }

        for(int i=0;i<n;i++){
            if(vec[i]*(i+1)<n){
                s.erase(s.lower_bound(vec[i]*(i+1)) , s.upper_bound((vec[i]+1)*(i+1)-1));
            }
        }

        cout<<s.size()<<'\n';
        for(auto it:s){
            cout<<it<<' ';
        }
        cout<<'\n';
    }
    return 0;
}
