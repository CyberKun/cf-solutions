#include <bits/stdc++.h>
using namespace std;
#define ll long long
const int MOD = 998244353;

int main(){
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int t;
    cin >> t;

    while (t--){
        ll n, x;
        cin >> n >> x;

        ll A0 = 1 + (x / 4);
        ll R0 = (n + 1) / 4 - (x / 4);

        ll A1 = (x + 2) / 4;
        ll R1 = (n + 3) / 4 - ((x + 2) / 4);

        A0 %= MOD;
        R0 %= MOD;
        A1 %= MOD;
        R1 %= MOD;

        ll ans = (A0 * R0) % MOD;
        ans = (ans + (A1 * R1) % MOD) % MOD;

        cout << ans << '\n';
    }

    return 0;
}