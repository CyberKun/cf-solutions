#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t;
    cin >> t;

    while (t--) {
        ll n;
        cin>>n;
        vector<ll>vec(n);
        for (int i=0;i<n;i++)cin>>vec[i];

        int ct=0;
        for(int i=0;i<n;i++){
            if(vec[i]==0)ct++;
        }
        int ans=2;
        if(vec[0]==0)ans--;
        if(vec[n-1]==0)ans--;

        if(ct<2)cout<<-1<<'\n';
        else cout<<ans<<'\n';
    }
    return 0;
}
