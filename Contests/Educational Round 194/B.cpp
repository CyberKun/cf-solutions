#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t;
    cin >> t;

    while (t--) {
        ll x,y,k;
        cin>>y>>x>>k;

        if(x<2*y){
            cout<<(x%y)*k<<'\n';
            continue;
        }

        ll ans=0;
        while(k>0&&x>=2*y){
            ans+=(x%y);
            x++;
            y++;
            k--;
        }

        ans+=(x%y)*k;
        cout<<ans<<'\n';
    }
    return 0;
}
