#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t;
    cin >> t;

    while (t--) {
        ll n;
        cin >> n;
        vector<ll> vec(n);
        for (int i = 0; i < n; i++) cin >> vec[i];
        int ans1=0,ans2=0,ans3=0;
        for(int i=0;i<n;i++){
            if(vec[i]%2==1)ans1++;
            else if(vec[i]%4==0)ans2++;
            else ans3++;
        }
        cout<<max({ans1,ans2,ans3})<<'\n';
    }
    return 0;
}
