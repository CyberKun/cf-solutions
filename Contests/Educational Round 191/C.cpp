#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main()
{
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll t;
    cin >> t;

    while (t--)
    {
        ll n, k;
        cin >> n >> k;
        string s;
        cin >> s;

        ll ct = 0 , cnt = 0; 

        for (int i = 0; i < n; i++) {
            if (s[i] == '(') {
                ct++;
            }
            else {
                if (ct > 0) {
                    ct--;
                }
                else {
                    cnt = i + 1;
                }
            }
        }

        string ans(n, '0');
        for (int i = 0; i < cnt && k > 0; i++){
            if (s[i] == '(') {
                ans[i] = '1';
                k--;
            }
        }

        for (int i = n - 1; i >= cnt && k > 0; i--){
            if (s[i] == ')') {
                ans[i] = '1';
                k--;
            }
        }

        cout << ans << '\n';
    }
    return 0;
}