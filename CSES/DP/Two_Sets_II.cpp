#include <bits/stdc++.h>
using namespace std;
#define ll long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    ll n;
    cin >> n;
    ll sumo = (n*(n+1))/2;
    if(sumo%2) {
        cout<<0<<'\n';
        return 0;
    }
    vector<vector<ll>>dp(n+1,vector<ll>(sumo/2+1,0));
    for(int i=0;i<n;i++) dp[i][0]=1;
    dp[1][1]=1;
    for(int i=2;i<=n;i++) {
        for(int j=1;j<=(sumo/2);j++) {
            dp[i][j]=dp[i-1][j];
            if(j>=i) dp[i][j]=(dp[i][j]+dp[i-1][j-i])%(1000000007);
        }
    }
    cout<<dp[n-1][(sumo/2)]<<'\n';
    return 0;
}
